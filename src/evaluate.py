def save_frame(filename, frame):
    cv2.imwrite(filename, frame)

def make_env():
    """
    Create one environment instance and wrap it with Monitor
    so episode rewards and lengths are logged automatically.
    """
    env = CatheterEnv(precomputed_goals=precomputed_goals, max_steps_per_goal=60, goal_tolerance_px=45)
    env = FilterObservation(env, filter_keys=['goal_xy', 'spline_points', 'current_insertion_cm', 'current_rotation_rad'])
    env = Monitor(env)
    return env

def delete_bin_files(directory_path: str):
    folder = Path(directory_path)

    if not folder.exists() or not folder.is_dir():
        return
    
    count = 0

    for file_path in folder.glob('*.bin'):
        try:
            file_path.unlink()
            count += 1
        except Exception as e:
            print(f"failed to delete {file_path}: {e}")

        print(f"deleted {count} files")

def main():
    # Start ROS before creating the environment
    rclpy.init()

    # Make sure output folders exist before training starts
    os.makedirs("eval_videos", exist_ok=True)

    env = make_env()

    try:
        model = SAC.load("models_local_goals_2/sac_catheter_env2_final.zip", env=env)

        episodes_to_run = 20
        episodes_completed = 0
        step_in_episode = 0

        obs, info = env.reset()
        while episodes_completed < episodes_to_run:
            action, _states = model.predict(obs, deterministic=True)
            obs, reward, terminated, truncated, info = env.step(action)

            frame = env.render()

            if frame is not None:
                if not os.path.exists(f"eval_videos_2/episode_{episodes_completed:04d}"):
                    os.makedirs(f"eval_videos_2/episode_{episodes_completed:04d}", exist_ok=True)
                # print(frame)
                save_frame(f"eval_videos_2/episode_{episodes_completed:04d}/step_{step_in_episode:04d}.png", frame)

            step_in_episode += 1

            if terminated or truncated:
                episodes_completed += 1
                step_in_episode = 0
                obs, info = env.reset()

    finally:
        env.close()

        if rclpy.ok():
            rclpy.shutdown()


if __name__ == "__main__":
    main()